const NBSP = ' ';
/** Соединитель слов: невидимый знак, который запрещает перенос строки в этом месте. */
const WORD_JOINER = '⁠';

// Предлоги, союзы и частицы, после которых строка не должна обрываться.
const shortWords = /(^|[\s«(])([А-Яа-яЁёA-Za-z]{1,2}|для|без|при|над|под|про|или) /g;

/**
 * Русская типографика для текстов страницы: неразрывный пробел после коротких слов,
 * чтобы строка не заканчивалась предлогом или союзом, и запрет переноса после «ИИ-»,
 * чтобы слово «ИИ-автоматизаций» не разрывалось по дефису.
 */
export function typograph(text: string): string {
    let result = text.replace(/ИИ-/g, `ИИ-${WORD_JOINER}`);
    // Короткие слова могут идти подряд («и в»), поэтому замена повторяется до неподвижной точки.
    let previous: string;
    do {
        previous = result;
        result = result.replace(shortWords, `$1$2${NBSP}`);
    } while (result !== previous);
    return result;
}
